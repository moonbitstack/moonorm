#!/usr/bin/env python3
"""Write the vectors the MoonBit side replays, from the two references.

`integration/reference` holds two runs of other implementations:

  * SQLAlchemy 2.0 declares the same two tables, seeds the same rows and answers the
    same ten queries;
  * Alembic 1.16 reads one model change off a live database and lists the operations
    it would generate.

This script turns both runs into the artefacts the repository keeps:

  * `integration/reference/expected/*.txt` — the transcripts, readable as text;
  * `integration/realdb/src/reference_expected.mbt` — the same lines as MoonBit
    arrays, which is what the tests compare against.

`--check` regenerates them in a temporary directory and fails if the tree holds
something else, so a vector cannot drift from the reference that produced it.

    python3 scripts/gen_reference_vectors.py [--check]
"""

from __future__ import annotations

import argparse
import difflib
import pathlib
import subprocess
import sys
import tempfile

ROOT = pathlib.Path(__file__).resolve().parent.parent
REFERENCE = ROOT / "integration" / "reference"
EXPECTED = REFERENCE / "expected"
FIXTURE = ROOT / "integration" / "realdb" / "src" / "reference_expected.mbt"


def _emit(directory: pathlib.Path) -> None:
    subprocess.run(
        [sys.executable, str(REFERENCE / "run.py"), "emit", "--dir", str(directory)],
        check=True,
    )
    subprocess.run(
        [sys.executable, str(REFERENCE / "alembic_ops.py"), "emit", "--dir", str(directory)],
        check=True,
    )


def _constant(name: str, lines: list[str]) -> str:
    # A multi-line literal rather than an array literal: `moon fmt` reflows arrays
    # and leaves `#|` blocks exactly as written, and these lines are the vector.
    body = "\n".join(f"  #|{line}" for line in lines)
    return f"///|\npub let {name}_text : String =\n{body}\n"


def _fixture(directory: pathlib.Path) -> str:
    schema = open(directory / "sa_schema.txt", encoding="utf-8", newline="").read().splitlines()
    queries = open(directory / "sa_queries.txt", encoding="utf-8", newline="").read().splitlines()
    reads = open(directory / "sa_reads.txt", encoding="utf-8", newline="").read().splitlines()
    ops = open(directory / "alembic_ops.txt", encoding="utf-8", newline="").read().splitlines()
    header = (
        "// What SQLAlchemy 2.0 and Alembic 1.16 answer for the same declaration and the\n"
        "// same model change: one line per schema fact, one per result row, one per\n"
        "// migration operation. Generated by scripts/gen_reference_vectors.py; edit the\n"
        "// reference, not this.\n\n"
    )
    return (
        header
        + _constant("expected_reference_schema", schema)
        + "\n"
        + _constant("expected_reference_transcript", queries)
        + "\n"
        + _constant("expected_reference_reads", reads)
        + "\n"
        + _constant("expected_reference_alembic_ops", ops)
    )


def _write(path: pathlib.Path, text: str) -> None:
    # Generated files are compared byte for byte on three systems: LF, always.
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(text)


def generate() -> dict[pathlib.Path, str]:
    """The files to write, keyed by path."""
    with tempfile.TemporaryDirectory() as raw:
        directory = pathlib.Path(raw)
        _emit(directory)
        return {
            EXPECTED / "schema.txt": open(directory / "sa_schema.txt", encoding="utf-8", newline="").read(),
            EXPECTED / "queries.txt": open(directory / "sa_queries.txt", encoding="utf-8", newline="").read(),
            EXPECTED / "reads.txt": open(directory / "sa_reads.txt", encoding="utf-8", newline="").read(),
            EXPECTED / "alembic_ops.txt": open(directory / "alembic_ops.txt", encoding="utf-8", newline="").read(),
            FIXTURE: _fixture(directory),
        }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    wanted = generate()
    if not args.check:
        for path, text in wanted.items():
            _write(path, text)
            print(f"wrote {path.relative_to(ROOT)}")
        return 0
    stale = False
    for path, text in wanted.items():
        current = (
            open(path, encoding="utf-8", newline="").read() if path.exists() else ""
        )
        if current == text:
            continue
        stale = True
        print(f"{path.relative_to(ROOT)} is not what the reference produces:")
        sys.stdout.writelines(
            difflib.unified_diff(
                current.splitlines(keepends=True),
                text.splitlines(keepends=True),
                fromfile="committed",
                tofile="regenerated",
            )
        )
    if stale:
        print("run scripts/gen_reference_vectors.py and commit the result")
        return 1
    print("the vectors match the reference")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
